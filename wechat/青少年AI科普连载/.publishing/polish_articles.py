def tidy_terms(line):
    terms=r'(?:Transformer|Chinchilla|ResNet|Gopher|GPipe|softmax|token|sRGB|RGB|LSTM|CNN|RNN|NTM|RAG|MDL|MMLU|UNESCO|AI|D1)'
    line=re.sub(r'([\u4e00-\u9fff])('+terms+r')',r'\1 \2',line)
    line=re.sub(r'('+terms+r')([\u4e00-\u9fff])',r'\1 \2',line)
    return line

def main():
    audit=[]
    with ZipFile(BACKUP) as z:
        for d in sorted(ROOT.glob('[0-9][0-9]_*')):
            if not d.is_dir():continue
            number=int(d.name[:2]);rel=str((d/'公众号_排版用.md').relative_to(ROOT))
            original=z.read(rel).decode();body,refs=original.split('## 资料来源',1)
            old_lines=[s for s in body.splitlines() if s.strip()];new_lines=[];changes=[]
            for i,line in enumerate(old_lines):
                if i in EDITS[number]:
                    assert not line.startswith(('#','![','*','>')), (number,i,'protected paragraph')
                    value=EDITS[number][i]
                    assert Counter(re.findall(r'〔[\d,]+〕',line))==Counter(re.findall(r'〔[\d,]+〕',value)),(number,i,'citation drift')
                    changes.append({'paragraph':i,'before':line,'after':value})
                else:value=line
                if not value.startswith(('#','![')):value=value.replace('。”。','。”')
                if not value.startswith(('#','![','*')):value=tidy_terms(value)
                new_lines.append(value)
            result='\n\n'.join(new_lines)+'\n\n## 资料来源'+refs
            # Explicitly preserve all metadata needed to keep the revised art in sync.
            assert re.findall(r'^#+ .*',original,re.M)==re.findall(r'^#+ .*',result,re.M)
            assert re.findall(r'^!\[.*',original,re.M)==re.findall(r'^!\[.*',result,re.M)
            assert result.split('## 资料来源',1)[1]==refs
            (d/'公众号_排版用.md').write_text(result)
            audit.append({'article':number,'paragraphs_rewritten':len(changes),'changes':changes})
    (ROOT/'.publishing/article_polish_audit.json').write_text(json.dumps(audit,ensure_ascii=False,indent=2))
    print('Polished',len(audit),'articles;',sum(a['paragraphs_rewritten'] for a in audit),'paragraphs rewritten; titles, figures and sources retained')

